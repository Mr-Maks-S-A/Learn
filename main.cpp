/**
 * @mainpage Программа "Обратный пузырёк"
 * @section desc Описание
 * Программа инициализирует массив из 10 чисел и сортирует его,
 * прогоняя минимальные элементы в начало массива (обратный пузырек).
 *
 * @author Салакатов Максим Альбертович aka (Jarko || Mr-Maks-S-A)
 */


#include <iostream> // Для потоков ввода/вывода (std::cout)
#include <cstdlib>  // Для макроса EXIT_SUCCESS
#include <clocale>  // Библиотека для работы с локалью (setlocale)


/**
 * @brief Точка входа в программу.
 * * @details Процесс работы:
 * 1. Инициализация неупорядоченного массива.
 * 2. Вывод исходного состояния массива.
 * 3. Сортировка методом "обратного пузырька" (проход с конца в начало).
 * 4. Вывод отсортированного массива.
 *
 * @return int Статус завершения программы (EXIT_SUCCESS в случае успеха).
 */
int main() {
    // Проверка на Windows (макрос _WIN32 определен и в 32, и в 64-битных системах)
    #ifdef _WIN32
    std::setlocale(LC_ALL, "Russian");
    #endif

    const int size = 10;
    int arr[size] = {10, 3, 4, 1, 8, 9, 7, 2, 6, 5};

    // 1. Вывод массива до сортировки
    std::cout << "Массив до сортировки: ";
    for (int i = 0; i < size; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;

    // 2. Сортировка "Обратный пузырек"
    bool swapped;
    do {
        swapped = false;
        // Идем с конца массива (индекс size - 1) до второго элемента (индекс 1)
        for (int i = size - 1; i > 0; --i) {
            // Если текущий элемент меньше предыдущего — меняем их местами
            if (arr[i] < arr[i - 1]) {
                int temp = arr[i];
                arr[i] = arr[i - 1];
                arr[i - 1] = temp;
                swapped = true; // Фиксируем, что была замена
            }
        }
    } while (swapped); // Повторяем, пока массив не станет стабильным

    // 3. Вывод массива после сортировки
    std::cout << "Массив после сортировки: ";
    for (int i = 0; i < size; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;


    return EXIT_SUCCESS;
}
