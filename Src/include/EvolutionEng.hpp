/**
 * @file EvolutionEng.hpp
 * @brief Заголовочный файл движка эволюции клеточного автомата.
 *
 * Содержит определения топологий и основной класс EvolutionEng,
 * отвечающий за вычисление новых поколений игрового мира.
 */

#pragma once
#include "World.hpp"


struct Rules {
    bool birth[9]   = {false}; ///< Индекс N true, если клетка рождается при N соседях.
    bool survive[9] = {false}; ///< Индекс N true, если клетка выживает при N соседях.
    bool parse_rules(const std::string& input);
};


/**
 * @enum Topology
 * @brief Тип геометрии (топологии) игрового пространства.
 */
enum class Topology {
    Toroidal,  ///< Замкнутая поверхность (тор): края соединены друг с другом.
    Bounded    ///< Ограниченная плоскость: выход за границы считается "пустотой".
};

/**
 * @class EvolutionEng
 * @brief Вычислительное ядро клеточного автомата.
 *
 * Класс инкапсулирует правила игры и алгоритмы подсчета соседей в зависимости
 * от выбранной топологии мира.
 */
class EvolutionEng {
public:
    Rules rules;            ///< Текущий набор правил рождения и выживания клеток.
    Topology topology = Topology::Toroidal; ///< Текущая топология пространства.

    /**
     * @brief Конструктор по умолчанию движка эволюции.
     */
    EvolutionEng();

    /**
     * @brief Деструктор движка эволюции.
     */
    ~EvolutionEng();

    /**
     * @brief Выполняет один шаг симуляции (вычисление нового поколения).
     *
     * Метод производит ротацию слоев истории в объекте World, вычисляет
     * новые состояния клеток и обновляет статус мира.
     *
     * @param world Ссылка на объект мира, который необходимо обновить.
     * @return true, если мир продолжает развиваться (есть живые клетки и нет стагнации).
     * @return false, если мир погиб или зациклился.
     */
    bool step(World& world);

private:
    /**
     * @brief Подсчет соседей по принципу тора.
     *
     * Если координата соседа выходит за границы массива, она переносится
     * на противоположную сторону поля.
     *
     * @param world Ссылка на текущий мир.
     * @param x Координата X текущей клетки.
     * @param y Координата Y текущей клетки.
     * @return int Количество живых соседей (0-8).
     */
    inline int count_neighbors_toroidal(const World& world, uint32_t x, uint32_t y);

    /**
     * @brief Подсчет соседей на ограниченной плоскости.
     *
     * Соседи за пределами границ (ширины/высоты) игнорируются.
     *
     * @param world Ссылка на текущий мир.
     * @param x Координата X текущей клетки.
     * @param y Координата Y текущей клетки.
     * @return int Количество живых соседей (0-8).
     */
    inline int count_neighbors_bounded(const World& world, uint32_t x, uint32_t y);

    /**
     * @brief Применение правил клеточного автомата к конкретной клетке.
     *
     * Обновляет статус жизни и инкрементирует возраст клетки при выживании.
     *
     * @param old_c Ссылка на состояние клетки в предыдущем поколении.
     * @param new_c Ссылка на записываемое состояние в новом поколении.
     * @param neighbors Количество живых соседей вокруг клетки.
     */
    inline void apply_rules(const Cell& old_c, Cell& new_c, int neighbors);
};


#include "EvolutionEng.inl"
